-- Smart CGM family sync (Cloudflare D1). Tokens are stored only as SHA-256 hashes.
CREATE TABLE IF NOT EXISTS patients (id TEXT PRIMARY KEY, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS tokens (
  hash TEXT PRIMARY KEY, patient TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('OWNER','ADMIN','VIEWER')),
  name TEXT NOT NULL DEFAULT '', created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS tokens_patient ON tokens(patient);
CREATE TABLE IF NOT EXISTS invites (
  code TEXT PRIMARY KEY, patient TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('ADMIN','VIEWER')), expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS readings (patient TEXT NOT NULL, t INTEGER NOT NULL, mgdl INTEGER NOT NULL, PRIMARY KEY (patient, t));
CREATE TABLE IF NOT EXISTS status (patient TEXT PRIMARY KEY, json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT, patient TEXT NOT NULL, type TEXT NOT NULL, value REAL NOT NULL, t INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS proposals (patient TEXT PRIMARY KEY, low REAL NOT NULL, high REAL NOT NULL, t INTEGER NOT NULL);
